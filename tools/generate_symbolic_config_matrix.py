#!/usr/bin/env python3
"""Generate Markdown matrices comparing symbolic config defaults."""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
import json
from pathlib import Path
from typing import Dict, List, Tuple

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[1]

KEY_PATHS: List[Tuple[str, str]] = [
    ("symbolic.enabled", "Symbolic enabled"),
    ("symbolic.device", "Symbolic device"),
    ("symbolic.search_strategy", "Search strategy"),
    ("symbolic.max_depth", "Max depth"),
    ("symbolic.max_expansions", "Max expansions"),
    ("symbolic.max_nodes", "Max nodes"),
    ("symbolic.beam_width", "Beam width"),
    ("symbolic.soft_timeout_s", "Soft timeout (s)"),
    ("symbolic.hard_timeout_s", "Hard timeout (s)"),
    ("symbolic.heuristics.mode", "Heuristic mode"),
    ("symbolic.heuristics.neural.enabled", "Neural heuristic"),
    ("symbolic.heuristics.neural.model_path", "Heuristic model"),
    ("symbolic.heuristics.calibration.scale", "Heuristic calibration scale"),
    ("symbolic.egraph.enabled", "E-graph enabled"),
    ("symbolic.smt.enabled", "SMT gateway"),
    ("symbolic.smt.timeout_per_candidate", "SMT timeout per candidate"),
    ("symbolic.smt.issue_tokens", "SMT token issuance"),
    ("symbolic.symmetry.enabled", "Symmetry normalization"),
    ("symbolic.cegis.enabled", "CEGIS enabled"),
    ("symbolic.coordination.enabled", "Coordination hooks"),
    ("symbolic.engineering.enabled", "Engineering guardrails"),
    ("symbolic.telemetry.progress_file", "Telemetry progress path"),
    ("symbolic.frontier.report_dir", "Frontier report dir"),
]


def load_config(path: Path) -> Dict[str, object]:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"Config {path} did not parse into a mapping.")
    return data


def pluck(data: Dict[str, object], path: str) -> object:
    cursor: object = data
    for part in path.split("."):
        if not isinstance(cursor, dict):
            return "-"
        cursor = cursor.get(part, "-")
        if cursor is None:
            return "-"
    if isinstance(cursor, (dict, list)):
        return json.dumps(cursor, sort_keys=True)
    return cursor


def build_table(configs: Dict[str, Path]) -> str:
    loaded = {name: load_config(path) for name, path in configs.items()}
    headers = ["Setting"] + list(configs.keys())
    lines = ["|" + "|".join(headers) + "|", "|" + "|".join(["---"] * len(headers)) + "|"]
    for key, label in KEY_PATHS:
        row = [label]
        for name in configs:
            row.append(str(pluck(loaded[name], key)))
        lines.append("|" + "|".join(row) + "|")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=PROJECT_ROOT / "docs" / "symbolic" / "config_matrix.md",
        help="Output Markdown path.",
    )
    parser.add_argument(
        "--configs",
        nargs="+",
        default=[
            f"default={PROJECT_ROOT / 'docs' / 'CONFIG_DEFAULTS.yaml'}",
            f"ablation_full={PROJECT_ROOT / 'configs' / 'generated' / 'ablation_full.yaml'}",
            f"eval_smoke={PROJECT_ROOT / 'configs' / 'eval' / 'smoke.yaml'}",
        ],
        help="List of name=path entries.",
    )
    args = parser.parse_args()

    pairs: Dict[str, Path] = {}
    for item in args.configs:
        name, _, path_str = item.partition("=")
        if not name or not path_str:
            raise ValueError(f"Malformed config spec: {item}")
        pairs[name] = Path(path_str).resolve()

    timestamp = datetime.now(tz=UTC).isoformat(timespec="seconds").replace("+00:00", "Z")
    table = build_table(pairs)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        "\n".join(
            [
                "<!-- Autogenerated by tools/generate_symbolic_config_matrix.py -->",
                f"_Updated: {timestamp}_",
                "",
                table,
                "",
                "Run `python3 tools/generate_symbolic_config_matrix.py` after changing configs.",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
